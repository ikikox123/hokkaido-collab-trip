export type MessageKey = keyof typeof catalog;

export type Vars = Record<string, string | number>;

export function formatMessage(template: string, vars?: Vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (token, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : token,
  );
}

export function text(locale: Locale, key: MessageKey, vars?: Vars) {
  return formatMessage(catalog[key][locale], vars);
}

export function intlLocale(locale: Locale) {
  if (locale === 'ja') return 'ja-JP';
  if (locale === 'en') return 'en-US';
  return 'zh-Hant-TW';
}

export function htmlLang(locale: Locale) {
  if (locale === 'ja') return 'ja';
  if (locale === 'en') return 'en';
  return 'zh-Hant';
}

export function mapsLanguage(locale: Locale) {
  if (locale === 'ja') return 'ja';
  if (locale === 'en') return 'en';
  return 'zh-TW';
}
